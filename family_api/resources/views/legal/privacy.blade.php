    <h2>2. เราใช้ข้อมูลเพื่อ</h2>
    <ul>
        <li>ให้บริการตามที่คุณเลือกใช้ เช่น แสดงตำแหน่งให้ครอบครัว แสดงโพสต์ และส่งแจ้งเตือนมาที่โทรศัพท์</li>
        <li>ดูแลความปลอดภัย ตรวจสอบรายงาน ป้องกันสแปม การโกง และการใช้งานที่ผิดกฎ</li>
        <li>ตรวจสอบร้านค้าก่อนเปิดขายในตลาด</li>
        <li>แก้ไขปัญหาและปรับปรุงแอป</li>
    </ul>
    <p>
        ฐานทางกฎหมายที่เราใช้ คือ การปฏิบัติตามสัญญาการให้บริการ ความยินยอมของคุณ (เช่น การเปิดใช้ตำแหน่ง)
        และประโยชน์โดยชอบด้วยกฎหมายในการดูแลความปลอดภัยของผู้ใช้
    </p>

    <h2>3. สิ่งที่เราไม่ทำ</h2>
    <ul>
        <li>ไม่ขายข้อมูลส่วนบุคคลของคุณ</li>
        <li>ไม่แสดงโฆษณา และไม่ส่งข้อมูลให้บริษัทโฆษณา</li>
        <li>ไม่เก็บประวัติตำแหน่ง และไม่ติดตามตำแหน่งตอนที่คุณปิดแอป</li>
        <li>แอปไม่ได้รับชำระเงินแทนผู้ซื้อหรือผู้ขายในตลาด จึงไม่เก็บข้อมูลบัตรหรือบัญชีธนาคาร</li>
    </ul>

    <h2>4. ผู้ให้บริการที่เกี่ยวข้อง</h2>
    <ul>
        <li><strong>ผู้ให้บริการคลาวด์:</strong> เก็บฐานข้อมูลและไฟล์รูปของแอป รูปทั้งหมดเก็บแบบส่วนตัว และเปิดดูได้ผ่านลิงก์ชั่วคราวเท่านั้น</li>
        <li><strong>Google Maps:</strong> ใช้แสดงแผนที่ในแอป การใช้แผนที่เป็นไปตาม<a href="https://policies.google.com/privacy" rel="noopener">นโยบายความเป็นส่วนตัวของ Google</a></li>
        <li><strong>Google, LINE และ Facebook:</strong> ใช้ยืนยันตัวตนเมื่อคุณเลือกเข้าสู่ระบบด้วยบัญชีเหล่านั้น
            เราขอเฉพาะชื่อ อีเมล และรหัสบัญชี และไม่โพสต์หรือเข้าถึงข้อมูลอื่นในบัญชีของคุณ
            ยกเลิกการเชื่อมได้ที่ ตั้งค่า → บัญชีที่เชื่อมต่อ</li>
        <li><strong>Google Firebase:</strong> Cloud Messaging ใช้ส่งแจ้งเตือนมาที่โทรศัพท์ และ Crashlytics ใช้รับรายงานเมื่อแอปเด้ง
            Google ประมวลผลข้อมูลนี้แทนเราตาม<a href="https://firebase.google.com/support/privacy" rel="noopener">ข้อกำหนดความเป็นส่วนตัวของ Firebase</a></li>
    </ul>
    <p>เราอาจเปิดเผยข้อมูลเมื่อกฎหมายกำหนด หรือเมื่อเจ้าหน้าที่รัฐร้องขอตามอำนาจที่ถูกต้อง</p>

    <h2>5. ระยะเวลาเก็บข้อมูล</h2>
    <ul>
        <li>เราเก็บข้อมูลจนกว่าคุณจะลบเนื้อหานั้น หรือลบบัญชี</li>
        <li>เมื่อคุณส่งคำขอลบบัญชี เราจะลบให้ภายใน {{ \App\Models\AccountDeletionRequest::PROCESS_WITHIN_DAYS }} วัน
            โดยบัญชี โปรไฟล์ ตำแหน่ง โพสต์ ความคิดเห็น แชท กิจกรรม ร้านค้า สินค้า และรูปทั้งหมดของคุณจะถูกลบ
            (ถ้าคุณเป็นเจ้าของครอบครัวคนเดียว ครอบครัวจะถูกลบด้วย)</li>
        <li>ข้อความแชทถูกลบเมื่อคุณกดยกเลิกการส่ง หรือเมื่อบัญชีของคุณหรือคู่สนทนาถูกลบ</li>
        <li>หลังลบบัญชี เราเก็บเฉพาะชื่อ อีเมล และวันที่ของคำขอลบไว้เป็นหลักฐานการดำเนินการ</li>
        <li>รหัสเครื่องสำหรับแจ้งเตือนถูกลบเมื่อคุณออกจากระบบ / การแจ้งเตือนที่อ่านแล้วถูกลบเมื่อเก่ากว่า 90 วัน</li>
        <li>รายงานเมื่อแอปเด้งเก็บไว้ที่ Firebase ประมาณ 90 วัน</li>
        <li>สำเนาสำรองของระบบอาจยังมีข้อมูลอยู่ระยะหนึ่งตามรอบการสำรองข้อมูล ก่อนถูกลบออกโดยอัตโนมัติ</li>
    </ul>

    <h2>6. สิทธิ์ของคุณ</h2>
    <p>คุณมีสิทธิ์ขอเข้าถึง ขอสำเนา แก้ไข ลบ ระงับการใช้ หรือคัดค้านการใช้ข้อมูลของคุณ และถอนความยินยอมได้ตลอดเวลา</p>
    <ul>
        <li>แก้ไขชื่อและรูปโปรไฟล์ได้เองในหน้าโปรไฟล์</li>
        <li>ปิดการแชร์ตำแหน่งได้ในหน้าตั้งค่าของแอป หรือปิดการเข้าถึงตำแหน่งในการตั้งค่าของโทรศัพท์</li>
        <li>เลือกประเภทการแจ้งเตือนได้ในหน้าตั้งค่าของแอป หรือปิดการแจ้งเตือนทั้งหมดในการตั้งค่าของโทรศัพท์</li>
        <li>ขอลบบัญชีได้ในแอป (ตั้งค่า → ขอลบบัญชี) หรือที่ <a href="{{ route('account.delete') }}">{{ route('account.delete') }}</a></li>
        <li>หากเห็นว่าเราใช้ข้อมูลไม่ถูกต้อง คุณร้องเรียนต่อสำนักงานคณะกรรมการคุ้มครองข้อมูลส่วนบุคคล (สคส.) ได้</li>
    </ul>

